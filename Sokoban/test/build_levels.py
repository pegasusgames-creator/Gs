#!/usr/bin/env python3
"""build_levels.py — assemble Sokoban's 500-level campaign + daily pool and
write them into the LEVELS region of game.html.

Sources (all deterministic, all pull-generated = solvable by construction):
  * gen_levels.py          — the original 500-map onboarding set (2026-06).
                             Levels 1-100 are CURATED from it: a ramp from a
                             one-crate, four-move opener to its densest
                             four-crate rooms (the rest are near-duplicates
                             of each other and too shallow for later play).
  * data/mined.json        — gen_campaign.js: 8 bands x 50 deeper rooms
                             (levels 101-500), each the deepest state of a
                             reverse pull-BFS, picked for box switching.
  * data/daily.json        — gen_campaign.js daily: 3 weekday tiers x 60.
  * data/solutions.json    — solve_levels.js cache: move-optimal LURD per map
                             (weighted-A* best-known line where the optimum
                             is out of budget).

Within each 50-level chapter, levels are ordered by solution length so every
chapter ramps. verify_levels.py replays every stored line before shipping and
scripts/check_sokoban_solvable.py re-proves each map with A*.

    python3 Sokoban/test/build_levels.py          # rewrites the LEVELS region
    python3 Sokoban/test/build_levels.py --dry-run
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
GAME = REPO / "Sokoban/android/app/src/main/assets/game.html"
DATA = HERE / "data"

sys.path.insert(0, str(HERE))
import gen_levels  # noqa: E402


def rle(s):
    return re.sub(r"([udlrUDLR])\1+", lambda m: f"{len(m.group(0))}{m.group(1)}", s)


def boxes_of(m):
    return m.count("$") + m.count("*")


def curate_onboarding(maps, sol):
    """100 levels: 1-15 one crate, 16-50 two crates, 51-100 three-four."""
    seen, uniq = set(), []
    for m in maps:
        if m in seen or m not in sol:
            continue
        seen.add(m)
        uniq.append(m)

    def mv(m):
        return sol[m]["moves"]

    def pick(pool, n, lo=0):
        pool = [m for m in pool if mv(m) >= lo]
        # deepest n (stable on generation order), then easy -> hard
        pool = sorted(pool, key=lambda m: -mv(m))[:n]
        return sorted(pool, key=lambda m: (mv(m), sol[m]["pushes"]))

    one = [m for m in uniq if boxes_of(m) == 1]
    two = [m for m in uniq if boxes_of(m) == 2]
    many = [m for m in uniq if boxes_of(m) >= 3]
    # opener: three gentle one-crate rooms (4, 5, 6 moves) so levels 1-3
    # clear in well under 30 s, then the deepest one-crate rooms.
    opener = []
    for target in (4, 5, 6):
        for m in one:
            if mv(m) == target and m not in opener and sol[m]["pushes"] >= 2:
                opener.append(m)
                break
    rest_one = pick([m for m in one if m not in opener], 12, lo=6)
    out = opener + rest_one + pick(two, 35) + pick(many, 50)
    assert len(out) == 100 and len(set(out)) == 100, len(out)
    return out


def main():
    dry = "--dry-run" in sys.argv
    sol = json.loads((DATA / "solutions.json").read_text())
    onboarding = curate_onboarding(gen_levels.build_levels(), sol)
    mined = json.loads((DATA / "mined.json").read_text())
    chapters = []
    for b in range(8):
        band = [L["map"] for L in mined if L["band"] == b]
        assert len(band) == 50, (b, len(band))
        missing = [m for m in band if m not in sol]
        if missing:
            sys.exit(f"band {b}: {len(missing)} maps have no solution — "
                     f"run solve_levels.js first")
        chapters.append(sorted(band, key=lambda m: sol[m]["moves"]))
    levels = onboarding + [m for ch in chapters for m in ch]
    assert len(levels) == 500 and len(set(levels)) == 500

    daily = json.loads((DATA / "daily.json").read_text())
    tiers = [[L["map"] for L in daily if L["band"] == t] for t in range(3)]
    for t in tiers:
        assert all(m in sol for m in t), "daily map without solution"
        assert not set(t) & set(levels), "daily map duplicates a campaign level"

    def js_maps(ms, indent=""):
        return (",\n" + indent).join("`" + m + "`" for m in ms)

    opt = sum(1 for m in levels if sol[m]["optimal"])
    region = (
        "// LEVELS (500 levels)\n"
        "// ============================================================\n"
        "// Sokoban campaign — generated by Sokoban/test/build_levels.py; do not\n"
        "// hand-edit. Every map is pull-generated (solvable by construction) and\n"
        "// re-proved by scripts/check_sokoban_solvable.py. SOLUTIONS[i] is the\n"
        f"// move-optimal LURD line ({opt}/500; the rest best-known via weighted A*),\n"
        "// run-length encoded; par = its length. verify_levels.py replays them.\n"
        "// Chapters 1-2: curated from the original onboarding set; 3-10: mined\n"
        "// by gen_campaign.js (deepest reverse-pull states). DAILY = 3 weekday\n"
        "// tiers (Mon-Tue / Wed-Fri / Sat-Sun) mined with a separate seed.\n"
        "const LEVELS=[\n" + js_maps(levels) + "\n];\n"
        "const SOLUTIONS=[\n" + ",\n".join("'" + rle(sol[m]["lurd"]) + "'" for m in levels) + "\n];\n"
        "const DAILY=[\n" + ",\n".join("[\n" + js_maps(t) + "\n]" for t in tiers) + "\n];\n"
        "const DAILY_SOL=[\n" + ",\n".join(
            "[" + ",".join("'" + rle(sol[m]["lurd"]) + "'" for m in t) + "]" for t in tiers) + "\n];\n"
        "const CAMPAIGN = LEVELS; // length contract for level-select/addendum\n"
    )
    if dry:
        print(f"levels 500 (optimal {opt}), daily {[len(t) for t in tiers]}, "
              f"region {len(region)} bytes")
        for i in (0, 1, 2, 99, 100, 499):
            print(i + 1, sol[levels[i]]["moves"], "moves")
        return
    tmp = HERE / "data" / ".levels_region.txt"
    tmp.write_text(region)
    subprocess.run([sys.executable, str(REPO / "scripts/shell_region.py"),
                    "Sokoban", "LEVELS", "--set", str(tmp)], check=True)
    tmp.unlink()
    print(f"wrote LEVELS region: 500 levels ({opt} move-optimal), "
          f"daily {[len(t) for t in tiers]}")


if __name__ == "__main__":
    main()
