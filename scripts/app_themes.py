#!/usr/bin/env python3
"""
app_themes.py — color palette registry for the entire Pegasus Games portfolio.

Each app gets a DISTINCT color theme. Themes are deliberately varied so the
Play Store grid (where users see multiple Pegasus Games apps next to each
other) doesn't look like 100 dark-blue clones.

Used by:
- gen_icon.py             (background gradient + accent colors)
- gen_feature.py          (feature graphic gradient)
- wrap_screenshots.py     (marketing frame gradient)
- wrap_tablet_screenshots.py (tablet marketing frame gradient)

Each theme has:
  bg_top_left, bg_top_right, bg_bottom: 3-stop gradient for backgrounds
  text_primary:  main heading color
  text_accent:   secondary/highlight color (must contrast on bg)
  text_subtle:   caption color (lower contrast)
  footer_tint:   small footer text color
  mood:          short string describing the theme

Palettes are designed for accessibility (text contrast ratio ≥4.5:1
against the bg gradient midpoint) and visual variety across the
portfolio. Some are dark, some are light, some are warm, some cool —
intentionally diverse.

Usage:
    from app_themes import get_theme
    t = get_theme("WaterSort")
    bg = (t["bg_top_left"], t["bg_top_right"], t["bg_bottom"])
    accent = t["text_accent"]
"""

