def get_theme(app_name):
    """Return the theme dict for an app. Falls back to hash-cycled palette
    if not registered."""
    if app_name in THEMES:
        return THEMES[app_name]
    # Hash the app name to a deterministic fallback theme
    idx = sum(ord(c) for c in app_name) % len(FALLBACK_THEMES)
    return FALLBACK_THEMES[idx]


def list_themes():
    """Print all themes in the registry. Used for visual review."""
    print(f"Registered themes: {len(THEMES)}")
    for app, t in sorted(THEMES.items()):
        bg = t["bg_top_left"]
        archs = []
        for k in ("layout_archetype", "mascot_pattern", "voice", "texture"):
            v = t.get(k)
            if v:
                archs.append(v)
        arch_str = "/".join(archs) if archs else "(no archetypes set)"
        print(f"  {app:25s} {t['mood']:25s} {arch_str:20s} "
              f"bg=#{bg[0]:02x}{bg[1]:02x}{bg[2]:02x}")
    print(f"\nFallback themes: {len(FALLBACK_THEMES)}")
    for i, t in enumerate(FALLBACK_THEMES):
        print(f"  fallback[{i}]: {t['mood']}")


def audit_archetype_distribution():
    """Audit the portfolio's archetype distribution against APP_ARCHETYPES.md
    targets. Surfaces when too many apps share an archetype.

    Targets:
        Layout: A=30%, B=15%, C=10%, D=10%, E=10%, F=10%, G=5%, H=5%, I=5%
        Mascot: M0=30%, M1=30%, M2=20%, M3=10%, M4=10%
        Voice:  no more than 25% on any one voice
        Texture: T1 max 40%, others spread
    """
    from collections import Counter
    layouts = Counter()
    mascots = Counter()
    voices = Counter()
    textures = Counter()
    missing = []

    for app, t in THEMES.items():
        layout = t.get("layout_archetype")
        mascot = t.get("mascot_pattern")
        voice = t.get("voice")
        texture = t.get("texture")
        if not all([layout, mascot, voice, texture]):
            missing.append(app)
            continue
        layouts[layout] += 1
        mascots[mascot] += 1
        voices[voice] += 1
        textures[texture] += 1

    n = len(THEMES) - len(missing)
    if n == 0:
        print("No apps have archetypes set yet.")
        if missing:
            print(f"Apps missing archetypes: {missing}")
        return

    print(f"Archetype distribution across {n} app(s) with archetypes set:")
    print()

    def pct(count):
        return 100.0 * count / n

    print("Layout archetype:")
    for arch, count in sorted(layouts.items()):
        bar = "█" * count
        print(f"  {arch}: {bar} {count} ({pct(count):.0f}%)")
    if pct(layouts.get("A", 0)) > 30 and n >= 5:
        print("  WARNING: Layout A exceeds 30%. Next app should pick a different layout.")

    print()
    print("Mascot pattern:")
    for arch, count in sorted(mascots.items()):
        bar = "█" * count
        print(f"  {arch}: {bar} {count} ({pct(count):.0f}%)")
    if pct(mascots.get("M0", 0)) > 40 and n >= 5:
        print("  WARNING: M0 (no mascot) exceeds 40%. Next app should have a mascot.")

    print()
    print("Voice:")
    for arch, count in sorted(voices.items()):
        bar = "█" * count
        print(f"  {arch}: {bar} {count} ({pct(count):.0f}%)")
    for v, c in voices.items():
        if pct(c) > 25 and n >= 5:
            print(f"  WARNING: Voice {v} exceeds 25%. Vary voice for next app.")

    print()
    print("Texture:")
    for arch, count in sorted(textures.items()):
        bar = "█" * count
        print(f"  {arch}: {bar} {count} ({pct(count):.0f}%)")
    if pct(textures.get("T1", 0)) > 40 and n >= 5:
        print("  WARNING: T1 (flat clean) exceeds 40%. Try T2-T8 for next app.")

    if missing:
        print()
        print(f"Apps missing archetype fields ({len(missing)}):")
        for app in missing:
            print(f"  - {app}")
        print("Update each app's THEMES entry with layout_archetype, "
              "mascot_pattern, voice, and texture fields.")


